package guidance

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

const uiGuidancePath = "../../../ui/src/features/insights/authoring-guidance.ts"

var updateUIGuidance = flag.Bool("update", false, "rewrite "+uiGuidancePath+" from the Go guidance lists")

// renderUIGuidance is the exact TypeScript source for the Build with AI copy.
// Strings are JSON-encoded, which is valid JavaScript for quote-free lines.
func renderUIGuidance(t *testing.T) string {
	t.Helper()
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/insights/guidance; DO NOT EDIT.\n")
	out.WriteString("// Regenerate with: go test ./internal/insights/guidance -run TestAuthoringGuidanceTypeScriptIsGenerated -update\n\n")
	list := func(name string, lines []string) {
		out.WriteString("export const " + name + ": readonly string[] = [\n")
		for _, line := range lines {
			encoded, err := json.Marshal(line)
			require.NoError(t, err)
			out.WriteString("  " + string(encoded) + ",\n")
		}
		out.WriteString("]\n")
	}
	// Only the composition list reaches the Build with AI prompt. Workflow rules
	// name MCP tools and must not reach it; the workflow list is generated here so
	// the file records every shared rule, but the UI does not import it.
	list("dashboardCompositionGuidance", DashboardComposition())
	out.WriteString("\n")
	list("dashboardWorkflowGuidance", DashboardWorkflow())
	return out.String()
}

// TestAuthoringGuidanceTypeScriptIsGenerated compares the whole generated file.
// Any reordering, added line or formatting change is a failure until regenerated.
func TestAuthoringGuidanceTypeScriptIsGenerated(t *testing.T) {
	want := renderUIGuidance(t)
	if *updateUIGuidance {
		require.NoError(t, os.WriteFile(uiGuidancePath, []byte(want), 0o600))
		return
	}
	got, err := os.ReadFile(uiGuidancePath)
	require.NoError(t, err)
	require.Equal(t, want, string(got), "authoring-guidance.ts is generated from internal/insights/guidance; run go test ./internal/insights/guidance -run TestAuthoringGuidanceTypeScriptIsGenerated -update")
}

func TestAuthoringGuidanceListsAreWellFormedAndSplit(t *testing.T) {
	composition, workflow := DashboardComposition(), DashboardWorkflow()
	// Composition carries the lint rule summaries plus the rules lint cannot check.
	require.GreaterOrEqual(t, len(composition), 8)
	require.LessOrEqual(t, len(composition), 18)
	require.GreaterOrEqual(t, len(workflow), 5)
	require.LessOrEqual(t, len(workflow), 10)
	seen := map[string]bool{}
	for _, line := range append(append([]string{}, composition...), workflow...) {
		require.True(t, strings.HasSuffix(line, "."), "rules end with a full stop: %s", line)
		require.NotContains(t, line, `"`, "rules stay quote-free: %s", line)
		require.NotContains(t, line, `\`, "rules stay backslash-free: %s", line)
		require.False(t, seen[line], "duplicate rule: %s", line)
		seen[line] = true
	}
	// Composition reaches the Build with AI prompt, which applies nothing and must
	// not be told to call MCP tools.
	for _, tool := range []string{"render_dashboard", "query_dashboard", "patch_dashboard", "get_dashboard", "NOT RUN"} {
		for _, line := range composition {
			require.NotContains(t, line, tool, "composition rules must not name MCP workflow: %s", line)
		}
	}
	joined := strings.Join(workflow, "\n")
	for _, required := range []string{"patch_dashboard", "get_dashboard", "query_dashboard", "render_dashboard", "NOT RUN", "1512px", "390px", "ETag"} {
		require.Contains(t, joined, required, "workflow rules must name %s", required)
	}
}

func TestAuthoringGuidanceListsAreIndependentCopies(t *testing.T) {
	first := DashboardComposition()
	first[0] = "mutated."
	require.NotEqual(t, "mutated.", DashboardComposition()[0], "callers must not mutate the shared composition rules")
	workflow := DashboardWorkflow()
	workflow[0] = "mutated."
	require.NotEqual(t, "mutated.", DashboardWorkflow()[0], "callers must not mutate the shared workflow rules")
}
