"""Reconstruct visible Edge mini-trace geometry as editable SVG fixture samples.

Values are normalized authored image coordinates, never recovered telemetry.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parent.parent
pixels=np.asarray(Image.open(ROOT/'docs/reference/edge-watch.png').convert('RGB')).astype(float)
def trace(bounds,kind,canvas_top,canvas_height):
 left,top,right,bottom=bounds
 values=[]
 for x in range(left,right+1):
  r,g,b=pixels[top:bottom,x].T
  if kind=='cyan': mask=(r<100)&(g>130)&(b>150);score=g+b-r
  elif kind=='violet':mask=(r>90)&(b>150)&(b>g*1.3);score=r+b-g
  elif kind=='red':mask=(r>160)&(g<130)&(b<130);score=r-g-b/2
  else:mask=(r>170)&(g>115)&(b<140);score=r+g-b
  hit=np.flatnonzero(mask)
  values.append(float(top+hit[np.argmax(score[hit])]) if len(hit) else None)
 known=[i for i,v in enumerate(values) if v is not None]
 ys=np.interp(np.arange(len(values)),known,[values[i] for i in known])
 return [round(canvas_height*(1-(y-canvas_top-3)/(canvas_height-7)),3) for y in ys]
series={
 'edgeMetricIngress':trace((291,171,449,200),'cyan',170,30),
 'edgeMetricEgress':trace((649,171,813,200),'violet',170,30),
 'edgeMetricBlocked':trace((1013,171,1174,200),'red',170,30),
 'edgeMetricConnections':trace((1373,171,1551,200),'amber',170,30),
 'edgeHistoryIngress':trace((731,414,943,440),'cyan',413,25),
 'edgeHistoryEgress':trace((731,449,943,479),'violet',448,25),
}
out='// Authored reference pixel geometry, not measured telemetry.\n// Generated by scripts/trace-reference-mini-profiles.py; missing pixel hits are interpolated.\n'
for name,values in series.items():out+=f'export const {name}: readonly number[] = '+json.dumps(values,separators=(',',':'))+';\n'
(ROOT/'src/reference/reference-mini-profiles.ts').write_text(out)
print('Wrote six authored Edge mini-trace profiles')
