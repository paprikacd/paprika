import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import { AUTH_TOKEN_KEY, LOGIN_PREFERENCE_KEY, SessionUnavailableError, bootstrapSession, clearRejectedSession, completeSession, ensureValidSession, exchangeAuthorizationCode, exchangePasswordForSession, forgetLoginPreference, getSessionSnapshot, logoutSession, readBrowserStorage, readLoginPreference, recoverUnauthorized, resetBrowserSessionForTests, syncSessionFromStorage } from "./browser-session"
const cache = vi.hoisted(() => ({ clear: vi.fn() }))
vi.mock("@/lib/query-provider", () => ({ clearBrowserQueryCache: cache.clear }))

function token(changes: Record<string, unknown> = {}) {
  return `e30.${btoa(JSON.stringify({ sub: "user-a", name: "Ada", email: "ada@example.test", iss: "issuer", aud: ["paprika-api"], iat: Math.floor(Date.now() / 1000), exp: Math.floor(Date.now() / 1000) + 3600, ...changes })).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "")}.sig`
}
const config = { oidc: { enabled: true, provider: "google", label: "Google" }, basic: { enabled: false }, session: { refreshEnabled: true } }
function json(value: unknown, status = 200) { return new Response(JSON.stringify(value), { status, headers: { "Content-Type": "application/json" } }) }
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>((r) => { resolve = r }); return { promise, resolve } }
let fetchMock: ReturnType<typeof vi.fn>
beforeEach(() => {
  localStorage.clear(); resetBrowserSessionForTests(); cache.clear.mockReset()
  Object.defineProperty(navigator, "locks", { configurable: true, value: { request: (_name: string, fn: () => unknown) => fn() } })
  fetchMock = vi.fn(async (url: string) => url === "/auth/config" ? json(config) : json({}, 401))
  vi.stubGlobal("fetch", fetchMock)
})
afterEach(() => { resetBrowserSessionForTests(); localStorage.clear(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

describe("browser sessions", () => {
  it("uses a valid persisted token immediately without a network roundtrip", async () => {
    const stored = token(); localStorage.setItem(AUTH_TOKEN_KEY, stored)
    expect(await bootstrapSession()).toBe(stored)
    expect(getSessionSnapshot().user?.name).toBe("Ada")
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it("restores a cookie-only session, never stores a provider refresh token", async () => {
    const fresh = token()
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : json({ idToken: fresh, sessionRefreshAvailable: true, refreshToken: "must-not-store" }))
    expect(await bootstrapSession()).toBe(fresh)
    expect(fetchMock).toHaveBeenCalledWith("/auth/refresh", expect.objectContaining({ credentials: "same-origin", headers: { "X-Paprika-Session": "1" } }))
    expect(Object.values(localStorage).join(" ")).not.toContain("must-not-store")
  })
  it("shares one refresh between concurrent callers", async () => {
    const expired = token({ exp: 1 }); localStorage.setItem(AUTH_TOKEN_KEY, expired)
    const fresh = token(); const pending = deferred<Response>()
    fetchMock.mockImplementation((url: string) => url === "/auth/config" ? Promise.resolve(json(config)) : pending.promise)
    const a = ensureValidSession(); const b = ensureValidSession()
    await vi.waitFor(() => expect(fetchMock.mock.calls.filter(([url]) => url === "/auth/refresh")).toHaveLength(1))
    pending.resolve(json({ idToken: fresh, sessionRefreshAvailable: true }))
    expect(await Promise.all([a, b])).toEqual([fresh, fresh])
  })
  it("preserves identity and cache across refresh, invalidates on authorization change", async () => {
    completeSession(token(), { method: "oidc", provider: "google", sessionRefreshAvailable: true })
    const before = getSessionSnapshot(); cache.clear.mockReset()
    const fresh = token({ iat: 123, exp: Math.floor(Date.now() / 1000) + 7200 })
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : json({ idToken: fresh, sessionRefreshAvailable: true }))
    await ensureValidSession({ forceRefresh: true })
    expect(getSessionSnapshot().identityKey).toBe(before.identityKey)
    expect(getSessionSnapshot().identityEpoch).toBe(before.identityEpoch)
    expect(cache.clear).not.toHaveBeenCalled()
    completeSession(token({ roles: ["admin"] }))
    expect(getSessionSnapshot().identityEpoch).toBe(before.identityEpoch + 1)
    expect(cache.clear).toHaveBeenCalledOnce()
  })
  it("does not reject a newer session because of a late 401", async () => {
    const old = token(); completeSession(old)
    const fresh = token({ exp: Math.floor(Date.now() / 1000) + 7200 }); completeSession(fresh)
    clearRejectedSession(old)
    expect(await recoverUnauthorized(old)).toBe(fresh)
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it.each([503, 403])("preserves identity and remembered account on temporary refresh status %s", async (status) => {
    const current = token(); completeSession(current, { method: "oidc", provider: "google", sessionRefreshAvailable: true })
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : json({}, status))
    await expect(recoverUnauthorized(current)).rejects.toBeInstanceOf(SessionUnavailableError)
    expect(getSessionSnapshot().status).toBe("unavailable")
    expect(getSessionSnapshot().user?.email).toBe("ada@example.test")
    expect(localStorage.getItem(AUTH_TOKEN_KEY)).toBe(current)
    expect(readLoginPreference()?.method).toBe("oidc")
  })
  it("removes credentials on a definitive refresh 401 but remembers the last successful account", async () => {
    const current = token(); completeSession(current, { method: "oidc", provider: "google", sessionRefreshAvailable: true })
    expect(await recoverUnauthorized(current)).toBeNull()
    expect(getSessionSnapshot().status).toBe("anonymous")
    expect(localStorage.getItem(AUTH_TOKEN_KEY)).toBeNull()
    expect(readLoginPreference()?.user.name).toBe("Ada")
    await ensureValidSession()
    expect(fetchMock.mock.calls.filter(([url]) => url === "/auth/refresh")).toHaveLength(1)
  })
  it("forgets the display hint without changing an authenticated session", () => {
    const current = token(); completeSession(current, { method: "oidc", provider: "google" })
    forgetLoginPreference()
    expect(localStorage.getItem(LOGIN_PREFERENCE_KEY)).toBeNull()
    expect(getSessionSnapshot().idToken).toBe(current)
  })
  it("blocks an in-flight refresh from reviving a signed-out session, including a delayed JSON body", async () => {
    completeSession(token(), { method: "oidc", provider: "google", sessionRefreshAvailable: true })
    const body = deferred<{ idToken: string }>()
    const parse = vi.fn(() => body.promise)
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : url === "/auth/logout" ? new Response(null, { status: 204 }) : { ok: true, status: 200, json: parse })
    const pending = ensureValidSession({ forceRefresh: true })
    await vi.waitFor(() => expect(parse).toHaveBeenCalled())
    await logoutSession()
    body.resolve({ idToken: token({ exp: Math.floor(Date.now() / 1000) + 7200 }) })
    expect(await pending).toBeNull()
    expect(getSessionSnapshot().status).toBe("anonymous")
    expect(localStorage.getItem(AUTH_TOKEN_KEY)).toBeNull()
  })
  it("blocks a callback response from reviving a logged-out session", async () => {
    const body = deferred<{ idToken: string }>()
    const parse = vi.fn(() => body.promise)
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : url === "/auth/logout" ? new Response(null, { status: 204 }) : { ok: true, status: 200, json: parse })
    const pending = exchangeAuthorizationCode({ code: "code", codeVerifier: "verifier", redirectUri: "https://console.test/auth/callback" }, "google")
    await vi.waitFor(() => expect(parse).toHaveBeenCalled())
    await logoutSession()
    body.resolve({ idToken: token() })
    await expect(pending).rejects.toThrow(/cancelled/)
    expect(getSessionSnapshot().status).toBe("anonymous")
  })
  it("fences password sign-in and removes the previous OIDC cookie before accepting a different account", async () => {
    const basicToken = token({ sub: "basic-user" })
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json({ ...config, basic: { enabled: true } }) : url === "/auth/basic-login" ? json({ idToken: basicToken }) : new Response(null, { status: 204 }))
    await exchangePasswordForSession({ username: "basic-user", password: "test-only" })
    expect(fetchMock.mock.calls.map(([url]) => url)).toEqual(["/auth/config", "/auth/basic-login", "/auth/logout"])
    expect(getSessionSnapshot().user?.sub).toBe("basic-user")
    expect(readLoginPreference()?.method).toBe("basic")
    expect(localStorage.getItem(LOGIN_PREFERENCE_KEY)).not.toContain("test-only")
  })
  it("does not resurrect a session after logout during password response decoding", async () => {
    const body = deferred<{ idToken: string }>()
    const parse = vi.fn(() => body.promise)
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json({ ...config, basic: { enabled: true } }) : url === "/auth/logout" ? new Response(null, { status: 204 }) : { ok: true, status: 200, json: parse })
    const pending = exchangePasswordForSession({ username: "basic-user", password: "test-only" })
    await vi.waitFor(() => expect(parse).toHaveBeenCalled())
    await logoutSession()
    body.resolve({ idToken: token({ sub: "basic-user" }) })
    await expect(pending).rejects.toThrow(/cancelled/)
    expect(getSessionSnapshot().status).toBe("anonymous")
  })
  it("marks configuration outages during unauthorized recovery as retryable", async () => {
    const current = token(); completeSession(current)
    fetchMock.mockRejectedValue(new TypeError("offline"))
    await expect(recoverUnauthorized(current)).rejects.toBeInstanceOf(SessionUnavailableError)
    expect(getSessionSnapshot().status).toBe("unavailable")
    expect(getSessionSnapshot().idToken).toBe(current)
  })
  it("synchronizes another tab's logout after completeSession, without a separate bootstrap", () => {
    completeSession(token(), { method: "oidc", provider: "google" })
    localStorage.setItem("paprika_session_state", JSON.stringify({ loggedOut: true, revision: "external-logout" }))
    window.dispatchEvent(new StorageEvent("storage", { key: "paprika_session_state" }))
    expect(getSessionSnapshot().status).toBe("anonymous")
    expect(readLoginPreference()?.user.name).toBe("Ada")
  })
  it("adopts same-user token changes from another tab without cache invalidation", () => {
    completeSession(token()); const epoch = getSessionSnapshot().identityEpoch; cache.clear.mockReset()
    const next = token({ exp: Math.floor(Date.now() / 1000) + 7200 }); localStorage.setItem(AUTH_TOKEN_KEY, next)
    syncSessionFromStorage(new StorageEvent("storage", { key: AUTH_TOKEN_KEY }))
    expect(getSessionSnapshot().idToken).toBe(next)
    expect(getSessionSnapshot().identityEpoch).toBe(epoch)
    expect(cache.clear).not.toHaveBeenCalled()
  })
  it.each(["null", "[]", "false", "invalid json"])("recovers from malformed stored state: %s", async (value) => {
    localStorage.setItem("paprika_session_state", value)
    expect(await bootstrapSession()).toBeNull()
    expect(getSessionSnapshot().status).toBe("anonymous")
  })
  it("keeps a usable in-memory session when storage reads and writes are denied", async () => {
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : new Response(null, { status: 204 }))
    vi.spyOn(Storage.prototype, "getItem").mockImplementation(() => { throw new Error("blocked") })
    vi.spyOn(Storage.prototype, "setItem").mockImplementation(() => { throw new Error("blocked") })
    vi.spyOn(Storage.prototype, "removeItem").mockImplementation(() => { throw new Error("blocked") })
    const current = token(); completeSession(current)
    expect(await ensureValidSession()).toBe(current)
    await logoutSession()
    expect(await ensureValidSession()).toBeNull()
  })
  it("preserves a logout tombstone when only storage writes fail", async () => {
    completeSession(token())
    vi.spyOn(Storage.prototype, "setItem").mockImplementation(() => { throw new Error("quota") })
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : new Response(null, { status: 204 }))
    await logoutSession()
    expect(JSON.parse(readBrowserStorage("paprika_session_state") ?? "{}").loggedOut).toBe(true)
    expect(await ensureValidSession()).toBeNull()
  })
  it("does not call unsupported logout on a basic-only deployment", async () => {
    completeSession(token(), { method: "basic", sessionRefreshAvailable: false })
    fetchMock.mockResolvedValue(json({ ...config, oidc: { ...config.oidc, enabled: false }, session: { refreshEnabled: false } }))
    await logoutSession()
    expect(fetchMock).toHaveBeenCalledTimes(1)
    expect(fetchMock).toHaveBeenCalledWith("/auth/config", expect.anything())
    expect(getSessionSnapshot().status).toBe("anonymous")
  })
  it("holds navigation while logout clears the cookie, but removes private identity immediately", async () => {
    completeSession(token())
    const response = deferred<Response>()
    fetchMock.mockImplementation((url: string) => url === "/auth/config" ? Promise.resolve(json(config)) : response.promise)
    const logout = logoutSession()
    expect(getSessionSnapshot()).toMatchObject({ status: "anonymous", user: null, logoutPending: true })
    await vi.waitFor(() => expect(fetchMock).toHaveBeenCalledWith("/auth/logout", expect.anything()))
    response.resolve(new Response(null, { status: 204 }))
    await logout
    expect(getSessionSnapshot().logoutPending).toBe(false)
  })
  it("uses an expiring storage lease when Web Locks are unavailable", async () => {
    Object.defineProperty(navigator, "locks", { configurable: true, value: undefined })
    const fresh = token()
    fetchMock.mockImplementation(async (url: string) => url === "/auth/config" ? json(config) : json({ idToken: fresh, sessionRefreshAvailable: true }))
    expect(await bootstrapSession()).toBe(fresh)
    expect(localStorage.getItem("paprika_session_lock")).toBeNull()
  })
})
